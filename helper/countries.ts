export function getStatesForCountry(countryName: string): string[] {
  if (!countryName) return COUNTRIES[0].states;
  const match = COUNTRIES.find(
    (c) => c.name.toLowerCase() === countryName.trim().toLowerCase() || c.code.toLowerCase() === countryName.trim().toLowerCase()
  );
  return match ? match.states : [];
}
